-- QuickSync: messages table, row level security, realtime and automatic cleanup.
--
-- Security model
--   * Every row belongs to exactly one auth user (user_id).
--   * RLS limits authenticated users to their own, unexpired rows.
--   * The anon role has no table privileges at all.
--   * Clients may only supply user_id, client_id and content on insert; timestamps are
--     always assigned by the database, so retention cannot be extended by a client.
--   * There is no UPDATE privilege: messages are immutable once sent.

-- ---------------------------------------------------------------------------
-- Table
-- ---------------------------------------------------------------------------

create table public.messages (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  -- Idempotency key generated by the sending device. A retried submission reuses the
  -- same key, so the unique constraint below turns retries into no-ops.
  client_id uuid not null,
  content text not null,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '24 hours'),

  constraint messages_content_not_blank check (content ~ '\S'),
  constraint messages_content_length check (char_length(content) <= 10000),
  constraint messages_expiry_after_creation check (expires_at > created_at),
  constraint messages_user_client_unique unique (user_id, client_id)
);

comment on table public.messages is 'Short-lived text snippets synced between a user''s devices.';
comment on column public.messages.client_id is 'Per-submission idempotency key generated by the client.';

-- Newest-first listing for a user (keyset pagination on created_at, id).
create index messages_user_created_idx on public.messages (user_id, created_at desc, id desc);
-- Cleanup job scans by expiry.
create index messages_expires_at_idx on public.messages (expires_at);

-- ---------------------------------------------------------------------------
-- Server-assigned timestamps
-- ---------------------------------------------------------------------------

create or replace function public.messages_set_timestamps()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.created_at := now();
  new.expires_at := now() + interval '24 hours';
  return new;
end;
$$;

create trigger messages_set_timestamps
  before insert on public.messages
  for each row execute function public.messages_set_timestamps();

-- ---------------------------------------------------------------------------
-- Privileges
-- ---------------------------------------------------------------------------

revoke all on table public.messages from anon, authenticated;
grant select, delete on table public.messages to authenticated;
grant insert (user_id, client_id, content) on table public.messages to authenticated;

-- ---------------------------------------------------------------------------
-- Row level security
-- ---------------------------------------------------------------------------

alter table public.messages enable row level security;

create policy "Users can read their own active messages"
  on public.messages
  for select
  to authenticated
  using ((select auth.uid()) = user_id and expires_at > now());

create policy "Users can create their own messages"
  on public.messages
  for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

create policy "Users can delete their own messages"
  on public.messages
  for delete
  to authenticated
  using ((select auth.uid()) = user_id);

-- ---------------------------------------------------------------------------
-- Realtime
-- ---------------------------------------------------------------------------
-- Postgres Changes evaluates the SELECT policy above for every subscriber, so a device
-- only receives INSERT events for its own user's rows. DELETE events cannot be checked
-- against RLS (the row is gone); with the default replica identity they carry only the
-- primary key, never the content.

alter publication supabase_realtime add table public.messages;

-- ---------------------------------------------------------------------------
-- Automatic cleanup
-- ---------------------------------------------------------------------------
-- Expired rows are already invisible through RLS. This job removes them physically so
-- nothing lingers in the database, even if no device ever opens the app again.

create or replace function public.purge_expired_messages()
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  deleted_count integer;
begin
  delete from public.messages where expires_at <= now();
  get diagnostics deleted_count = row_count;
  return deleted_count;
end;
$$;

comment on function public.purge_expired_messages() is
  'Deletes expired messages. Run by pg_cron; also callable by the service role as a fallback.';

revoke all on function public.purge_expired_messages() from public, anon, authenticated;
grant execute on function public.purge_expired_messages() to service_role;

create extension if not exists pg_cron with schema pg_catalog;

grant usage on schema cron to postgres;

-- Runs every 15 minutes. cron.schedule() upserts by job name, so re-running is safe.
select cron.schedule(
  'quicksync-purge-expired-messages',
  '*/15 * * * *',
  $$select public.purge_expired_messages();$$
);
